using System;
using System.Collections.Generic;
using System.Globalization;
using System.IO;
using System.IO.Compression;
using System.Linq;
using System.Text;
using System.Threading;
using LitJson;
using Mix.Games.Tray.Drop;
using UnityEditor;
using UnityEngine;

/// <summary>
/// Builds data/Drop_Data/Drop_Data.gz, the pattern catalog the Drop game
/// (winterwaltz) generates its endless level from (DropGame.IMixGame.Initialize:
/// LoadData("data/Drop_Data/Drop_Data.gz", "Drop_Data.txt", ParseJsonData), then
/// LevelGenerator.CreatePatterns(content.objects.Patterns)). The original
/// Drop_Data is lost, so this rebuilds it from hand-authored pattern files.
///
/// Rather than re-implementing the JSON schema, this uses the game's own classes:
/// each source file is parsed with PatternTemplate's built-in text parser (the
/// format the original designers authored in), converted with
/// PatternTemplate.ToPatternData(), and serialized with LitJson. The output is
/// therefore the same shape the game reads (PatternData / PlatformData).
/// Because it references those game classes, this file must compile in the same
/// assembly as them (Assets/Editor with no asmdefs, like the other builders).
///
/// SOURCE: one text file per pattern in Assets/Editor/DropPatterns/*.txt. The
/// file name (without extension) is the pattern's name/uid. Lines starting with
/// # are ignored. Format (PatternTemplate.LoadPatternTemplateFromString):
///
///   platform X Y ROTATION TYPE ENTER DURATION [FENCEBITS]    path platform, in order
///   decoy    X Y ROTATION TYPE ENTER DURATION [FENCEBITS]    decoy; attaches to the
///                                                            previous 'platform' (a decoy
///                                                            before any platform leads
///                                                            back to the connecting platform)
///   overlap 0.5          seconds the pattern starts before the previous one ends
///   next_pattern 2.0     seconds until the next pattern starts
///   reflect_x true|false     may be mirrored on X / Y at runtime
///   reflect_y true|false
///   rotate true|false        may be rotated 90 degrees at runtime
///   weight 100               optional; omitted = LevelGenerator.DefaultPatternWeight
///   include_after 0          optional; pattern number it first becomes eligible after
///   exclude_after 0          optional (the game's PatternData loader ignores it)
///
///   X Y        grid offset from the connecting platform
///   ROTATION   -1 (random) or 0..3
///   TYPE       a PlatformType name, case-sensitive: DEFAULT, SPIKES, QUICK, LONG
///   ENTER      seconds when the platform appears; DURATION = seconds it stays up
///   FENCEBITS  optional, FenceInfo.SetFromBits format (as written by FenceInfo.GetBits)
///
/// The game also needs a pattern whose name equals LevelGenerator.InitialPatternName
/// (set on the LevelGenerator in the Drop scene/prefab). Put the same name in
/// InitialPatternName below and the build verifies it exists.
///
/// If no source folder exists, it is created with one example pattern.
/// Variants (reflections, rotations) are generated by the game at load time, so
/// don't author them here.
/// </summary>
public static class DropDataBuilder
{
	// Must match LevelGenerator.InitialPatternName in the Drop scene. Empty = not verified (warning).
	private const string InitialPatternName = "start_pattern";

	private static string OutputPath { get { return Path.Combine(Application.streamingAssetsPath, "data/Drop_Data/Drop_Data.gz"); } }
	private static string SourceDir { get { return Path.Combine(Application.dataPath, "Editor/DropPatterns"); } }

	private const string ExampleName = "example_pattern";
	private const string ExampleText =
		"# Example pattern: three platforms in a row. Replace/delete and author your own.\n" +
		"# platform X Y ROTATION TYPE ENTER DURATION\n" +
		"platform 1 0 -1 DEFAULT 0 1.5\n" +
		"platform 2 0 -1 DEFAULT 0.3 1.5\n" +
		"platform 3 0 -1 DEFAULT 0.6 1.5\n" +
		"overlap 0\n" +
		"reflect_x true\n" +
		"reflect_y true\n" +
		"rotate true\n" +
		"next_pattern 0.9\n";

	[MenuItem("Tools/Mix/Games/Build Drop Data")]
	public static void Build()
	{
		string message;
		bool ok = TryBuild(out message);
		if (ok)
		{
			Debug.Log(message);
		}
		else
		{
			Debug.LogError(message);
		}
		EditorUtility.DisplayDialog("Drop Data", message, "OK");
	}

	/// <summary>For -batchmode: -executeMethod DropDataBuilder.BuildBatch (exit 1 on failure).</summary>
	public static void BuildBatch()
	{
		string message;
		bool ok = TryBuild(out message);
		Console.WriteLine(message);
		EditorApplication.Exit(ok ? 0 : 1);
	}

	public static bool TryBuild(out string message)
	{
		bool createdExample = false;
		if (!Directory.Exists(SourceDir) || Directory.GetFiles(SourceDir, "*.txt").Length == 0)
		{
			Directory.CreateDirectory(SourceDir);
			File.WriteAllText(Path.Combine(SourceDir, ExampleName + ".txt"), ExampleText, new UTF8Encoding(false));
			createdExample = true;
		}

		List<PatternData> patterns = new List<PatternData>();
		List<string> errors = new List<string>();
		List<string> warnings = new List<string>();

		CultureInfo oldCulture = Thread.CurrentThread.CurrentCulture;
		Thread.CurrentThread.CurrentCulture = CultureInfo.InvariantCulture; // the game's parser is culture-sensitive
		try
		{
			foreach (string file in Directory.GetFiles(SourceDir, "*.txt").OrderBy(f => f, StringComparer.Ordinal))
			{
				string name = Path.GetFileNameWithoutExtension(file);
				string text = File.ReadAllText(file, Encoding.UTF8);

				List<string> fileErrors = Validate(name, text, warnings);
				if (fileErrors.Count > 0)
				{
					errors.AddRange(fileErrors);
					continue;
				}

				PatternTemplate template = new PatternTemplate(text);
				template.Name = name; // the string constructor leaves the name blank
				if (template.PathPlatforms.Count == 0)
				{
					errors.Add(name + ": no 'platform' lines");
					continue;
				}
				PatternData data = template.ToPatternData();
				data.exclude_after = template.ExcludeAfter; // not copied by PatternData(PatternTemplate)
				patterns.Add(data);
			}
		}
		finally
		{
			Thread.CurrentThread.CurrentCulture = oldCulture;
		}

		if (errors.Count > 0)
		{
			message = "Not written. Fix these first:\n" + string.Join("\n", errors.ToArray());
			return false;
		}
		if (patterns.Count == 0)
		{
			message = "No patterns in " + SourceDir;
			return false;
		}

		bool initialFound = patterns.Any(p => p.uid == InitialPatternName);
		if (InitialPatternName.Length == 0)
		{
			warnings.Add("InitialPatternName not set in DropDataBuilder; make sure a pattern matches LevelGenerator.InitialPatternName");
		}
		else if (!initialFound)
		{
			message = "Not written. No pattern named '" + InitialPatternName + "' (LevelGenerator.InitialPatternName).";
			return false;
		}

		ContentObj root = new ContentObj
		{
			content = new Content { objects = new Objects { Patterns = patterns } }
		};
		string json;
		try
		{
			json = JsonMapper.ToJson(root);
			// Round-trip exactly as the game reads it.
			ContentObj check = JsonMapper.ToObject<ContentObj>(json);
			if (check.content.objects.Patterns.Count != patterns.Count)
			{
				message = "Not written. Round-trip pattern count mismatch.";
				return false;
			}
			foreach (PatternData pd in check.content.objects.Patterns)
			{
				new PatternTemplate(pd); // same conversion CreatePatterns performs
			}
		}
		catch (Exception e)
		{
			message = "Not written. JSON round-trip failed: " + e.Message;
			return false;
		}

		Directory.CreateDirectory(Path.GetDirectoryName(OutputPath));
		using (FileStream fs = File.Create(OutputPath))
		using (GZipStream gz = new GZipStream(fs, CompressionMode.Compress))
		{
			byte[] bytes = new UTF8Encoding(false).GetBytes(json);
			gz.Write(bytes, 0, bytes.Length);
		}
		AssetDatabase.Refresh();

		message = "Wrote " + OutputPath + ": " + patterns.Count + " patterns."
			+ (createdExample ? " Created example in " + SourceDir + "; author your own and run again." : "")
			+ (warnings.Count > 0 ? "\nWarnings:\n" + string.Join("\n", warnings.ToArray()) : "");
		return true;
	}

	// The game's parser swallows errors and returns a half-filled template, so check the source first.
	private static List<string> Validate(string name, string text, List<string> warnings)
	{
		List<string> errors = new List<string>();
		string[] lines = text.Split(new string[] { "\r\n", "\r", "\n" }, StringSplitOptions.None);
		List<int[]> path = new List<int[]>();
		HashSet<string> used = new HashSet<string>();

		for (int i = 0; i < lines.Length; i++)
		{
			string where = name + ":" + (i + 1) + ": ";
			string[] t = lines[i].Split(new char[] { ' ', '\t' }, StringSplitOptions.RemoveEmptyEntries);
			if (t.Length == 0 || t[0].StartsWith("#"))
			{
				continue;
			}
			switch (t[0].ToLower())
			{
				case "platform":
				case "decoy":
				{
					int x, y, rot;
					float enter, dur;
					if (t.Length < 7)
					{
						errors.Add(where + "expected: " + t[0] + " X Y ROTATION TYPE ENTER DURATION [FENCEBITS]");
						break;
					}
					if (!int.TryParse(t[1], out x) || !int.TryParse(t[2], out y))
					{
						errors.Add(where + "X and Y must be integers");
						break;
					}
					if (!int.TryParse(t[3], out rot) || rot < -1 || rot > 3)
					{
						errors.Add(where + "ROTATION must be -1..3");
					}
					PlatformType type;
					try
					{
						type = (PlatformType)Enum.Parse(typeof(PlatformType), t[4]);
						if (!Enum.IsDefined(typeof(PlatformType), type))
						{
							throw new ArgumentException();
						}
						if (type == PlatformType.NONE)
						{
							warnings.Add(where + "type NONE shows no platform mesh");
						}
					}
					catch (Exception)
					{
						errors.Add(where + "unknown TYPE '" + t[4] + "' (valid: " + string.Join(", ", Enum.GetNames(typeof(PlatformType))) + "; case-sensitive)");
					}
					if (!float.TryParse(t[5], out enter) || enter < 0f)
					{
						errors.Add(where + "ENTER must be a number >= 0");
					}
					if (!float.TryParse(t[6], out dur) || dur <= 0f)
					{
						errors.Add(where + "DURATION must be a number > 0");
					}
					if (!used.Add(x + "," + y))
					{
						warnings.Add(where + "grid cell (" + x + "," + y + ") is used more than once in this pattern");
					}
					if (t[0].ToLower() == "platform")
					{
						if (path.Count > 0)
						{
							int[] prev = path[path.Count - 1];
							if (Math.Abs(prev[0] - x) + Math.Abs(prev[1] - y) != 1)
							{
								warnings.Add(where + "path platform is not one grid step from the previous one (player may not be able to jump it)");
							}
						}
						path.Add(new int[] { x, y });
					}
					break;
				}
				case "reflect_x":
				case "reflect_y":
				case "rotate":
				{
					bool b;
					if (t.Length < 2 || !bool.TryParse(t[1], out b))
					{
						errors.Add(where + t[0] + " needs true or false");
					}
					break;
				}
				case "overlap":
				case "next_pattern":
				{
					float f;
					if (t.Length < 2 || !float.TryParse(t[1], out f))
					{
						errors.Add(where + t[0] + " needs a number");
					}
					break;
				}
				case "weight":
				case "include_after":
				case "exclude_after":
				{
					int n;
					if (t.Length < 2 || !int.TryParse(t[1], out n))
					{
						errors.Add(where + t[0] + " needs an integer");
					}
					break;
				}
				default:
					warnings.Add(where + "unknown keyword '" + t[0] + "' (ignored by the game)");
					break;
			}
		}
		if (path.Count == 0 && errors.Count == 0)
		{
			errors.Add(name + ": no 'platform' lines");
		}
		return errors;
	}
}